// Complete constant-time CDT leaf without MVE predicate instructions.
// Each unsigned 16-bit threshold is widened before subtraction, so
// (threshold - random) >> 31
// is one exactly when random > threshold and zero otherwise. The low and high
// halves are folded into one four-lane accumulator. q0-q3 are caller-saved;
// r2 retains the return address while lr owns the low-overhead loop.

.syntax unified
.thumb
.arch armv8.1-m.main
.arch_extension mve

.section .text.haetae_sample_gauss16_cdt_mve, "ax", %progbits
.align 2
.global haetae_sample_gauss16_cdt_mve
.type haetae_sample_gauss16_cdt_mve, %function
.thumb_func
haetae_sample_gauss16_cdt_mve:
        mov r2, lr
        vdup.32 q0, r0
        vmov.i32 q1, #0
        ldr r1, =haetae_asm_cdt16
        mov lr, #8
        dls lr, lr
                                       // Instructions:    18
                                       // Expected cycles: 32
                                       // Expected IPC:    0.56
                                       //
                                       // Cycle bound:     32.0
                                       // IPC bound:       0.56
                                       //
                                       // Wall time:     0.01s
                                       // User time:     0.01s
                                       //
                                       // ------ cycle (expected) ------->
                                       // 0                        25
                                       // |------------------------|------
        vldrh.U16 q2, [r1], #16        // *...............................
        vmovlt.U16 q3, q2              // .*..............................
        vsub.I32 q3, q3, q0            // ...*............................
        vmovlb.U16 q2, q2              // .....*..........................
        vshr.U32 q3, q3, #31           // .......*........................
        vsub.I32 q2, q2, q0            // .........*......................
        vshr.U32 q2, q2, #31           // ...........*....................
        vadd.U32 q2, q2, q3            // .............*..................
        vadd.U32 q1, q1, q2            // ...............*................
        vldrh.U16 q2, [r1], #16        // ................*...............
        vmovlt.U16 q3, q2              // .................*..............
        vmovlb.U16 q2, q2              // ...................*............
        vsub.I32 q3, q3, q0            // .....................*..........
        vshr.U32 q3, q3, #31           // .......................*........
        vsub.I32 q2, q2, q0            // .........................*......
        vshr.U32 q2, q2, #31           // ...........................*....
        vadd.U32 q2, q2, q3            // .............................*..
        vadd.U32 q1, q1, q2            // ...............................*

                                        // ------ cycle (expected) ------->
                                        // 0                        25
                                        // |------------------------|------
        // vldrh.U16 q2, [r1], #16      // *...............................
        // vmovlt.U16 q3, q2            // .*..............................
        // vsub.I32 q3, q3, q0          // ...*............................
        // vmovlb.U16 q2, q2            // .....*..........................
        // vshr.U32 q3, q3, #31         // .......*........................
        // vsub.I32 q2, q2, q0          // .........*......................
        // vshr.U32 q2, q2, #31         // ...........*....................
        // vadd.U32 q2, q2, q3          // .............*..................
        // vadd.U32 q2, q1, q2          // ...............*................
        // vldrh.U16 q1, [r1], #16      // ................*...............
        // vmovlt.U16 q3, q1            // .................*..............
        // vmovlb.U16 q1, q1            // ...................*............
        // vsub.I32 q3, q3, q0          // .....................*..........
        // vshr.U32 q3, q3, #31         // .......................*........
        // vsub.I32 q1, q1, q0          // .........................*......
        // vshr.U32 q1, q1, #31         // ...........................*....
        // vadd.U32 q1, q1, q3          // .............................*..
        // vadd.U32 q1, q2, q1          // ...............................*

        lsr lr, lr, #1
        sub lr, lr, #1
.p2align 2
haetae_sampler_mask_loop:
                                       // Instructions:    18
                                       // Expected cycles: 32
                                       // Expected IPC:    0.56
                                       //
                                       // Cycle bound:     32.0
                                       // IPC bound:       0.56
                                       //
                                       // Wall time:     0.11s
                                       // User time:     0.11s
                                       //
                                       // ------ cycle (expected) ------->
                                       // 0                        25
                                       // |------------------------|------
        vldrh.U16 q2, [r1], #16        // e...............................
        vmovlt.U16 q3, q2              // .e..............................
        vsub.I32 q3, q3, q0            // ...e............................
        vmovlb.U16 q2, q2              // .....e..........................
        vshr.U32 q3, q3, #31           // .......e........................
        vsub.I32 q2, q2, q0            // .........e......................
        vshr.U32 q2, q2, #31           // ...........e....................
        vadd.U32 q2, q2, q3            // .............e..................
        vadd.U32 q2, q1, q2            // ...............e................
        vldrh.U16 q1, [r1], #16        // ................e...............
        vmovlt.U16 q3, q1              // .................e..............
        vmovlb.U16 q1, q1              // ...................e............
        vsub.I32 q3, q3, q0            // .....................e..........
        vshr.U32 q3, q3, #31           // .......................e........
        vsub.I32 q1, q1, q0            // .........................e......
        vshr.U32 q1, q1, #31           // ...........................e....
        vadd.U32 q1, q1, q3            // .............................e..
        vadd.U32 q1, q2, q1            // ...............................e

                                        // ------- cycle (expected) ------->
                                        // 0                        25
                                        // |------------------------|-------
        // vldrh.u16 q2, [r1], #16      // e...............................'
        // vmovlt.u16 q3, q2            // .e..............................'
        // vmovlb.u16 q2, q2            // .....e..........................'
        // vsub.i32 q2, q2, q0          // .........e......................'
        // vsub.i32 q3, q3, q0          // ...e............................'
        // vshr.u32 q2, q2, #31         // ...........e....................'
        // vshr.u32 q3, q3, #31         // .......e........................'
        // vadd.u32 q2, q2, q3          // .............e..................'
        // vadd.u32 q1, q1, q2          // ...............e................'
        // vldrh.u16 q2, [r1], #16      // ................e...............'
        // vmovlt.u16 q3, q2            // .................e..............'
        // vmovlb.u16 q2, q2            // ...................e............'
        // vsub.i32 q2, q2, q0          // .........................e......'
        // vsub.i32 q3, q3, q0          // .....................e..........'
        // vshr.u32 q2, q2, #31         // ...........................e....'
        // vshr.u32 q3, q3, #31         // .......................e........'
        // vadd.u32 q2, q2, q3          // .............................e..'
        // vadd.u32 q1, q1, q2          // ...............................e'

        le lr, haetae_sampler_mask_loop
                // Instructions:    0
                // Expected cycles: 0
                // Expected IPC:    0.00
                //
                // Wall time:     0.00s
                // User time:     0.00s
                //
        movs r0, #0
        vaddva.u32 r0, q1
        movs r1, #0
        bx r2
.size haetae_sample_gauss16_cdt_mve, .-haetae_sample_gauss16_cdt_mve
