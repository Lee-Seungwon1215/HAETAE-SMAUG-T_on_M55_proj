// Complete HAETAE q=64513 pointwise/R-inverse public leaf normalized for
// Slothy.  The full d8-d15 save protects every callee-saved MVE register that
// Slothy may allocate while software-pipelining the loop.

.syntax unified
.thumb
.arch armv8.1-m.main
.arch_extension mve

.macro haetae_barrett value, quotient
        vqrdmulh.s32 \quotient, \value, r4
        vmla.s32     \value,    \quotient, r5
.endm

.section .text.haetae_pointwise_mve, "ax", %progbits
.align 2
.global haetae_pointwise_mve
.type haetae_pointwise_mve, %function
.thumb_func
