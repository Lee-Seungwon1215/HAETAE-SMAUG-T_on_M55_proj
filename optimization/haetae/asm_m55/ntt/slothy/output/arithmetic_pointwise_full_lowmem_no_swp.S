// Complete HAETAE q=64513 pointwise/R-inverse public leaf for a low-memory
// Slothy schedule. q4-q7 are reserved when this input is scheduled, so the
// public function uses caller-saved q0-q3 only and needs no MVE stack frame.

.syntax unified
.thumb
.arch armv8.1-m.main
.arch_extension mve

.macro haetae_barrett value, quotient
        vqrdmulh.s32 \quotient, \value, r4
        vmla.s32     \value,    \quotient, r5
.endm

.section .text.haetae_pointwise_mve, "ax", %progbits
.align 2
.global haetae_pointwise_mve
.type haetae_pointwise_mve, %function
.thumb_func
haetae_pointwise_mve:
        push {r4-r8, lr}
        movw r4, #33288
        movw r5, #64513
        rsb r5, r5, #0
        ldr r6, =-14127
        ldr r7, =-470254080
        mov lr, #64
        dls lr, lr
.p2align 2
haetae_pointwise_full_lowmem_loop:
                                       // Instructions:    13
                                       // Expected cycles: 21
                                       // Expected IPC:    0.62
                                       //
                                       // Cycle bound:     21.0
                                       // IPC bound:       0.62
                                       //
                                       // Wall time:     0.06s
                                       // User time:     0.06s
                                       //
                                       // ----- cycle (expected) ------>
                                       // 0                        25
                                       // |------------------------|----
        vldrw.U32 q0, [r1], #16        // *.............................
        vqrdmulh.S32 q2, q0, r4        // .*............................
        vldrw.U32 q1, [r2], #16        // ..*...........................
        vmla.S32 q0, q2, r5            // ...*..........................
        vqrdmulh.S32 q2, q1, r4        // .....*........................
        vmla.S32 q1, q2, r5            // .......*......................
        vmul.S32 q3, q0, q1            // .........*....................
        vqrdmulh.S32 q2, q3, r4        // ...........*..................
        vmla.S32 q3, q2, r5            // .............*................
        vmul.S32 q0, q3, r6            // ...............*..............
        vqrdmulh.S32 q2, q3, r7        // .................*............
        vmla.S32 q0, q2, r5            // ...................*..........
        vstrw.32 q0, [r0], #16         // ....................*.........

                                           // ------ cycle (expected) ------>
                                           // 0                        25
                                           // |------------------------|-----
        // vldrw.u32 q0, [r1], #16         // *..............................
        // vldrw.u32 q1, [r2], #16         // ..*............................
        // vqrdmulh.s32 q2, q0, r4         // .*.............................
        // vmla.s32     q0,    q2, r5      // ...*...........................
        // vqrdmulh.s32 q2, q1, r4         // .....*.........................
        // vmla.s32     q1,    q2, r5      // .......*.......................
        // vmul.s32 q0, q0, q1             // .........*.....................
        // vqrdmulh.s32 q2, q0, r4         // ...........*...................
        // vmla.s32     q0,    q2, r5      // .............*.................
        // vmul.s32 q1, q0, r6             // ...............*...............
        // vqrdmulh.s32 q2, q0, r7         // .................*.............
        // vmla.s32 q1, q2, r5             // ...................*...........
        // vstrw.32 q1, [r0], #16          // ....................*..........

        le lr, haetae_pointwise_full_lowmem_loop
        pop {r4-r8, lr}
        bx lr
.size haetae_pointwise_mve, .-haetae_pointwise_mve
