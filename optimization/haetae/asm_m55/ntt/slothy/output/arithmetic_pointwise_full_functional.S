// Complete HAETAE q=64513 pointwise/R-inverse public leaf normalized for
// Slothy.  The full d8-d15 save protects every callee-saved MVE register that
// Slothy may allocate while software-pipelining the loop.

.syntax unified
.thumb
.arch armv8.1-m.main
.arch_extension mve

.macro haetae_barrett value, quotient
        vqrdmulh.s32 \quotient, \value, r4
        vmla.s32     \value,    \quotient, r5
.endm

.section .text.haetae_pointwise_mve, "ax", %progbits
.align 2
.global haetae_pointwise_mve
.type haetae_pointwise_mve, %function
.thumb_func
haetae_pointwise_mve:
        push {r4-r8, lr}
        vpush {d8-d15}
        movw r4, #33288
        movw r5, #64513
        rsb r5, r5, #0
        ldr r6, =-14127
        ldr r7, =-470254080
        mov lr, #64
        dls lr, lr
.p2align 2
haetae_pointwise_full_loop:
                                       // Instructions:    13
                                       // Expected cycles: 13
                                       // Expected IPC:    1.00
                                       //
                                       // Wall time:     0.05s
                                       // User time:     0.05s
                                       //
                                       // ----- cycle (expected) ------>
                                       // 0                        25
                                       // |------------------------|----
        vldrw.U32 q0, [r1], #16        // *.............................
        vldrw.U32 q1, [r2], #16        // .*............................
        vqrdmulh.S32 q2, q0, r4        // ..*...........................
        vmla.S32 q0, q2, r5            // ...*..........................
        vqrdmulh.S32 q2, q1, r4        // ....*.........................
        vmla.S32 q1, q2, r5            // .....*........................
        vmul.S32 q0, q0, q1            // ......*.......................
        vqrdmulh.S32 q2, q0, r4        // .......*......................
        vmla.S32 q0, q2, r5            // ........*.....................
        vmul.S32 q1, q0, r6            // .........*....................
        vqrdmulh.S32 q2, q0, r7        // ..........*...................
        vmla.S32 q1, q2, r5            // ...........*..................
        vstrw.32 q1, [r0], #16         // ............*.................

                                           // ------ cycle (expected) ------>
                                           // 0                        25
                                           // |------------------------|-----
        // vldrw.u32 q0, [r1], #16         // *..............................
        // vldrw.u32 q1, [r2], #16         // .*.............................
        // vqrdmulh.s32 q2, q0, r4         // ..*............................
        // vmla.s32     q0,    q2, r5      // ...*...........................
        // vqrdmulh.s32 q2, q1, r4         // ....*..........................
        // vmla.s32     q1,    q2, r5      // .....*.........................
        // vmul.s32 q0, q0, q1             // ......*........................
        // vqrdmulh.s32 q2, q0, r4         // .......*.......................
        // vmla.s32     q0,    q2, r5      // ........*......................
        // vmul.s32 q1, q0, r6             // .........*.....................
        // vqrdmulh.s32 q2, q0, r7         // ..........*....................
        // vmla.s32 q1, q2, r5             // ...........*...................
        // vstrw.32 q1, [r0], #16          // ............*..................

        le lr, haetae_pointwise_full_loop
        vpop {d8-d15}
        pop {r4-r8, lr}
        bx lr
.size haetae_pointwise_mve, .-haetae_pointwise_mve
