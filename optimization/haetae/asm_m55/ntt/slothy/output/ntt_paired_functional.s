.macro haetae_mulmod dst, src, root, twisted
        vmul.s32       \dst,  \src, \root
        vqrdmulh.s32   \src,  \src, \twisted
        vmla.s32       \dst,  \src, modulus
.endm

.macro haetae_ct a, b, root, twisted
        haetae_mulmod tmp, \b, \root, \twisted
        vsub.u32       \b,    \a, tmp
        vadd.u32       \a,    \a, tmp
.endm

